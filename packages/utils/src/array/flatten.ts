/**
 * 将嵌套一层的数组扁平化为一维数组
 * 仅处理数组中的直接嵌套数组元素，不进行深度扁平化
 *
 * @template T - 数组元素的基础类型
 * @param array - 输入数组，包含基础类型元素和/或嵌套一层的数组
 * @returns 扁平化后的新数组，所有元素均为基础类型T
 * @example
 * flatten([1, [2, 3], 4]);
 * // 返回 [1, 2, 3, 4]
 * @example
 * flatten(['a', ['b', ['c']], 'd']);
 * // 返回 ['a', 'b', ['c'], 'd'] (仅扁平化一层，保留深层嵌套数组)
 * @example
 * flatten([[], [1, 2], 3]); // 返回 [1, 2, 3] (处理空数组)
 * @example
 * flatten([1, 2, 3]); // 返回 [1, 2, 3] (无嵌套数组时返回原数组元素)
 * @example
 * flatten([]); // 返回 [] (空输入数组)
 * **注意：** 与flattenDeep的区别：此函数仅扁平化一层，而flattenDeep会递归扁平化所有层级
 * **注意：** 函数返回新数组，不会修改原输入数组
 * **注意：** 非数组元素会被直接包含在结果中
 */
export const flatten = <T>(array: (T | T[])[]): T[] =>
  // 用 `flat(1)` 而非 `concat([], ...array)`：后者把每个元素当成一个实参展开，
  // 数组长度超过引擎的实参上限（V8 约 12 万）时直接 RangeError。
  // 两者对 hole 的处理一致（都会移除），语义等价（UTL-019）
  array.flat(1) as T[];
