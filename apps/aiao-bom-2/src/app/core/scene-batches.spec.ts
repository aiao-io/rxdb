import * as THREE from 'three';
import { describe, expect, it, vi } from 'vitest';
import { SceneBatches } from './scene-batches';

describe('整车批量绘制与原始发生位置分离', () => {
  it('共享几何只上传一次，世界变换与具体选择仍对应原始节点', () => {
    const scene = new THREE.Scene();
    const root = new THREE.Group();
    root.scale.setScalar(0.001);
    scene.add(root);
    const geometry = new THREE.BoxGeometry();
    const material = new THREE.MeshStandardMaterial();
    const first = new THREE.Mesh(geometry, material);
    const second = new THREE.Mesh(geometry, material);
    second.position.x = 2000;
    root.add(first, second);
    root.updateMatrixWorld(true);
    const batches = new SceneBatches(scene, [first, second]);
    const batch = scene.children.find(item => item instanceof THREE.BatchedMesh) as THREE.BatchedMesh;
    expect(batch).toBeDefined();
    expect(batch.instanceCount).toBe(2);
    expect(batch.unusedVertexCount).toBe(0);
    expect(batch.getMatrixAt(1, new THREE.Matrix4()).elements[12]).toBe(2);
    batches.update(new Set([first]), false, null);
    expect(batch.getVisibleAt(0)).toBe(false);
    expect(batch.getVisibleAt(1)).toBe(true);
    expect(first.layers.test(new THREE.PerspectiveCamera().layers)).toBe(true);
    expect(second.layers.test(new THREE.PerspectiveCamera().layers)).toBe(false);
    const ghost = new THREE.MeshBasicMaterial({ transparent: true, opacity: 0.1 });
    batches.update(new Set([first]), true, ghost);
    expect(batch.visible).toBe(false);
    batches.update(new Set([first]), false, ghost);
    expect(batch.material).toBe(ghost);
    batches.update(new Set(), false, null);
    expect(batch.material).toBe(material);
    expect(batch.getVisibleAt(0)).toBe(true);
    const dispose = vi.spyOn(batch, 'dispose');
    const sourceDispose = vi.spyOn(geometry, 'dispose');
    batches.dispose();
    expect(dispose).toHaveBeenCalledTimes(1);
    expect(sourceDispose).not.toHaveBeenCalled();
    expect(scene.children).not.toContain(batch);
    expect(first.layers.mask).toBe(1);
    geometry.dispose();
    material.dispose();
    ghost.dispose();
  });
  it('不同几何布局、镜像、带蒙皮和多材质节点保持原有绘制契约', () => {
    const scene = new THREE.Scene();
    const geometry = new THREE.BoxGeometry();
    const material = new THREE.MeshStandardMaterial();
    const mirrored = new THREE.Mesh(geometry, material);
    mirrored.scale.x = -1;
    const skinned = new THREE.SkinnedMesh(geometry, material);
    const multiple = new THREE.Mesh(geometry, [material]);
    const solo = new THREE.Mesh(geometry.clone().toNonIndexed(), material);
    scene.add(mirrored, skinned, multiple, solo);
    scene.updateMatrixWorld(true);
    const batches = new SceneBatches(scene, [mirrored, skinned, multiple, solo]);
    expect(scene.children).toHaveLength(4);
    batches.update(new Set([mirrored]), false, null);
    expect(mirrored.layers.mask).toBe(1);
    expect(solo.layers.mask).toBe(1);
    batches.dispose();
    geometry.dispose();
    solo.geometry.dispose();
    material.dispose();
  });
});
